/**
 * Preload the one webfont that renders the largest text on the page.
 *
 * @fontsource's @font-face rules are compiled INTO the CSS bundle, so the
 * browser cannot discover a single font file until that render-blocking
 * stylesheet has arrived and parsed. Preloading breaks that serial chain for
 * the headline face specifically.
 *
 * Only Space Grotesk 700 latin. The other nine faces (129 KB in total) stay
 * discovery-order: preloading is a promise that the file is needed immediately,
 * and spending mobile bandwidth on all of them would compete with the very
 * paint it is meant to accelerate. The header logo's latin-ext face is
 * deliberately not here — "KÖYLÜOĞLU" is 11px chrome, not content.
 *
 * The filename is content-hashed, so this has to run after the bundle exists.
 */
function injectFontPreload(html) {
  const assets = path.join(BUILD_DIR, 'assets');
  if (!fs.existsSync(assets)) return html;

  const face = fs
    .readdirSync(assets)
    .find((f) => /^space-grotesk-latin-700-normal-.*\.woff2$/.test(f));
  if (!face) {
    console.warn('⚠️  Space Grotesk 700 not found — skipping font preload');
    return html;
  }

  // crossorigin is REQUIRED on font preloads: fonts are always fetched in CORS
  // mode, and a non-CORS preload would be downloaded and then discarded.
  const link =
    `<link rel="preload" as="font" type="font/woff2" crossorigin ` +
    `href="/assets/${face}" />`;
  return html.replace('</head>', `  ${link}\n  </head>`);
}

function writeHtml(filePath, html) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, html, 'utf8');
}

function routeFile(routePath) {
  return routePath === '/'
    ? path.join(BUILD_DIR, 'index.html')
    : path.join(BUILD_DIR, routePath.replace(/^\//, ''), 'index.html');
}

function routeBody(routePath) {
  // Other routes paint the dark ground until React mounts — never the home hero.
  return routePath === '/' ? homeShell() : '';
}

function prerenderRoutes() {
  const indexPath = path.join(BUILD_DIR, 'index.html');
  if (!fs.existsSync(indexPath)) {
    console.warn('⚠️  build/index.html not found — skip prerender');
    return;
  }

  const baseHtml = injectFontPreload(fs.readFileSync(indexPath, 'utf8'));
  writeHtml(path.join(BUILD_DIR, 'app-shell.html'), baseHtml);
  console.log('✅ Wrote app-shell.html (article page template)');

  // Dynamic routes (/tech-news) are rendered per request by api/seo-page.js.
  for (const route of STATIC_ROUTES.filter((r) => !r.dynamic)) {
    const file = routeFile(route.path);
    try {
      writeHtml(file, renderPage(baseHtml, { ...route, bodyHtml: routeBody(route.path) }));
      console.log(`✅ Prerendered ${route.path}`);
    } catch (error) {
      // vercel.json rewrites these paths to the file, so it must exist.
      writeHtml(file, baseHtml);
      console.error(`⚠️  Prerender of ${route.path} failed, wrote plain shell:`, error.message);
    }
  }
}

try {
  prerenderRoutes();
} catch (error) {
  console.error('Prerender failed:', error.message);
  // Non-fatal: deploy should still succeed
  process.exitCode = 0;
}
